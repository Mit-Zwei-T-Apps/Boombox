#!/usr/bin/env python3
"""Generate the Pterodactyl egg for Boombox.

Usage:
    python3 scripts/make_egg.py OWNER/REPO [--author mail@example.com] [--output egg/egg-boombox.json]

The egg downloads boombox.tar.gz from the GitHub Releases of OWNER/REPO, so a fork only needs to
re-run this script with its own OWNER/REPO and upload the resulting JSON.
"""
import argparse
import json
import re
import sys
from datetime import datetime, timezone

DEFAULT_REPO = "Mit-Zwei-T-Apps/Boombox"
DEFAULT_AUTHOR = "matteomitzweit@proton.me"

INSTALL_SCRIPT = r"""#!/bin/ash
# Boombox installer. Runs in an Alpine container, installs into /mnt/server.
set -eu

apk add --no-cache curl ca-certificates tar >/dev/null

REPO="${GITHUB_REPO:-__DEFAULT_REPO__}"
TAG="${RELEASE_TAG:-latest}"

if ! printf '%s' "$REPO" | grep -Eq '^[A-Za-z0-9._-]+/[A-Za-z0-9._-]+$'; then
  echo "ERROR: GITHUB_REPO must look like OWNER/REPO."; exit 1
fi
if ! printf '%s' "$TAG" | grep -Eq '^(latest|[A-Za-z0-9._-]+)$'; then
  echo "ERROR: RELEASE_TAG may only contain letters, digits, dots, dashes and underscores."; exit 1
fi

if [ "$TAG" = "latest" ]; then
  BASE="https://github.com/${REPO}/releases/latest/download"
else
  BASE="https://github.com/${REPO}/releases/download/${TAG}"
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

echo "Downloading ${BASE}/boombox.tar.gz"
curl -fsSL --retry 3 -o "${TMP}/boombox.tar.gz" "${BASE}/boombox.tar.gz"

if curl -fsSL --retry 3 -o "${TMP}/boombox.tar.gz.sha256" "${BASE}/boombox.tar.gz.sha256"; then
  EXPECTED="$(cut -d' ' -f1 "${TMP}/boombox.tar.gz.sha256" | tr -d '[:space:]')"
  ACTUAL="$(sha256sum "${TMP}/boombox.tar.gz" | cut -d' ' -f1)"
  if [ "$EXPECTED" != "$ACTUAL" ]; then
    echo "ERROR: checksum mismatch, refusing to install."; exit 1
  fi
  echo "Checksum OK."
else
  echo "WARNING: no checksum file in this release, skipping verification."
fi

# Refuse archives with absolute paths, parent directory references or links.
if tar -tzf "${TMP}/boombox.tar.gz" | grep -Eq '(^/|(^|/)\.\.(/|$))'; then
  echo "ERROR: archive contains unsafe paths."; exit 1
fi
if tar -tvzf "${TMP}/boombox.tar.gz" | grep -Eq '^[lh]'; then
  echo "ERROR: archive contains links."; exit 1
fi

mkdir -p /mnt/server
cd /mnt/server

# Replace the app but keep data/ (accounts, sessions).
rm -rf server.js package.json lib public README.md
tar -xzf "${TMP}/boombox.tar.gz" -C /mnt/server

if [ ! -f server.js ] || [ ! -f lib/rooms.js ] || [ ! -f public/index.html ]; then
  echo "ERROR: archive is missing server.js or public/index.html."; exit 1
fi
mkdir -p data
echo "Boombox installed. Start the server to finish the setup."
""".replace("__DEFAULT_REPO__", DEFAULT_REPO)


def var(name, description, env, default, rules, editable=True):
    return {
        "name": name,
        "description": description,
        "env_variable": env,
        "default_value": default,
        "user_viewable": True,
        "user_editable": editable,
        "rules": rules,
        "field_type": "text",
    }


def build(repo, author):
    return {
        "_comment": "DO NOT EDIT: FILE GENERATED BY scripts/make_egg.py",
        "meta": {"version": "PTDL_v2", "update_url": None},
        "exported_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S+00:00"),
        "name": "Boombox",
        "author": author,
        "description": "Party games for a single phone (Impostor, Spy, Werewolf, Who would rather, Bomb) with optional accounts and several languages. Installs the latest release from GitHub.",
        "features": None,
        "docker_images": {
            "Node.js 22": "ghcr.io/parkervcp/yolks:nodejs_22",
            "Node.js 20": "ghcr.io/parkervcp/yolks:nodejs_20",
            "Node.js 18": "ghcr.io/parkervcp/yolks:nodejs_18",
        },
        "file_denylist": [],
        "startup": "node server.js",
        "config": {
            "files": "{}",
            "startup": "{\"done\": \"Boombox listening\"}",
            "logs": "{}",
            "stop": "^C",
        },
        "scripts": {
            "installation": {
                "script": INSTALL_SCRIPT.replace(DEFAULT_REPO, repo),
                "container": "alpine:3.20",
                "entrypoint": "ash",
            }
        },
        "variables": [
            var("GitHub repository", "Where the release archive is downloaded from, as OWNER/REPO.",
                "GITHUB_REPO", repo, "required|string|regex:/^[A-Za-z0-9._-]+\\/[A-Za-z0-9._-]+$/|max:100"),
            var("Release tag", "Version to install, for example v1.0.0, or latest. Change it and use Reinstall to update. The data folder is kept.",
                "RELEASE_TAG", "latest", "required|string|regex:/^(latest|[A-Za-z0-9._-]+)$/|max:50"),
            var("Allow registration", "Let visitors create accounts. Guests can always play without one.",
                "ALLOW_REGISTER", "true", "required|string|in:true,false"),
            var("Admin username", "Name of the admin account created on first start.",
                "ADMIN_USER", "admin", "required|string|regex:/^[A-Za-z0-9_.-]{3,24}$/"),
            var("Admin password", "Optional start password for the admin account. Leave empty for a random one in data/admin-initial-password.txt. It must be changed at the first login.",
                "ADMIN_PASSWORD", "", "nullable|string|min:8|max:128"),
            var("Secure cookies", "Set to true when the site is served over HTTPS (recommended).",
                "COOKIE_SECURE", "false", "required|string|in:true,false"),
            var("Trust proxy", "Set to true when a reverse proxy such as Nginx or Cloudflare sits in front, so the real client address is used for rate limits.",
                "TRUST_PROXY", "false", "required|string|in:true,false"),
            var("Maximum accounts", "Upper limit for registered accounts.",
                "MAX_USERS", "1000", "required|integer|min:1|max:100000"),
            var("Maximum rooms", "Upper limit for simultaneous online rooms.",
                "MAX_ROOMS", "200", "required|integer|min:1|max:5000"),
        ],
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("repo", nargs="?", default=DEFAULT_REPO, help="GitHub repository as OWNER/REPO")
    ap.add_argument("--author", default=DEFAULT_AUTHOR, help="email shown as egg author")
    ap.add_argument("--output", default="egg/egg-boombox.json")
    args = ap.parse_args()
    if not re.fullmatch(r"[A-Za-z0-9._-]+/[A-Za-z0-9._-]+", args.repo):
        sys.exit("ERROR: repository must look like OWNER/REPO")
    with open(args.output, "w", encoding="utf-8") as f:
        json.dump(build(args.repo, args.author), f, indent=4, ensure_ascii=False)
        f.write("\n")
    print("Wrote %s for %s" % (args.output, args.repo))


if __name__ == "__main__":
    main()
